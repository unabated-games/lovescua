"""Summarize the checked-in declarations generated from the real native registry."""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent
rows = []
for path in sorted((root / "decls").glob("*.scua")):
    signatures = re.findall(r"^fn (.+) end$", path.read_text(), re.MULTILINE)
    rows.append((path, signatures))
print("# SCUA native API inventory\n")
print("Generated by `python3 scua/api_inventory.py`. Declarations come from "
      "`build/lovescua --write-decls scua/decls`; the host test checks they match the executable.\n")
print(f"**{sum(len(signatures) for _, signatures in rows)} native functions across {len(rows)} modules.** "
      "This is a count of exposed entry points, not a percentage of LÖVE compatibility. "
      "Overloads and object methods use SCUA-oriented signatures.\n")
print("| Module | Functions | Declarations |\n| --- | ---: | --- |")
for path, signatures in rows:
    print(f"| `{path.stem}` | {len(signatures)} | [{path.name}](scua/decls/{path.name}) |")
print("\nThe SCUA `filesystem` facade adds resource and opt-in save operations over the "
      "language's `fs` capability. It is imported separately so games without file access need no grant.\n")
for path, signatures in rows:
    print(f"## {path.stem}\n\n```scua")
    print("\n".join(signatures))
    print("```\n")
